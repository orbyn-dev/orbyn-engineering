#!/usr/bin/env python3
"""Fail when a commit message credits an AI tool.

Commit messages in this repository carry no tool attribution: no `Co-Authored-By`
trailer for an assistant, no "Generated with" line, and no assistant address. AI use
is disclosed in the pull request's AI usage section instead (see CONTRIBUTING.md).

CI runs this over every commit a pull request adds, that is `BASE..HEAD`. It only
reads commit messages; it never runs anything from the pull request.
"""

import argparse
import re
import subprocess
import sys

# Tools and vendors whose name in a `Co-Authored-By` trailer is attribution to a tool.
TOOLS = (
    r"claude|anthropic|openai|chatgpt|codex|gpt|gemini|copilot|cursor|devin|aider|"
    r"windsurf|codeium|tabnine|amazon q|bedrock|llama|mistral|deepseek|grok|bard|"
    r"opencode|antigravity|sourcegraph|cody"
)

PATTERNS = [
    (
        re.compile(rf"^\s*co-authored-by:.*\b(?:{TOOLS})\b", re.IGNORECASE),
        "a Co-Authored-By trailer that names an AI tool",
    ),
    (
        re.compile(r"^\s*co-authored-by:.*@(?:anthropic|openai)\.com", re.IGNORECASE),
        "a Co-Authored-By trailer with an AI vendor address",
    ),
    (
        re.compile(r"noreply@(?:anthropic|openai)\.com", re.IGNORECASE),
        "an AI vendor's no-reply address",
    ),
    (
        # A line that starts with "Generated with" or "Generated by", after any emoji,
        # bullet or quote marks. A sentence that merely uses the words ("types generated
        # with ts-rs") does not start the line, so it passes.
        re.compile(r"^[^A-Za-z0-9]*generated (?:with|by)\b", re.IGNORECASE),
        'a "Generated with" line',
    ),
    (
        re.compile(r"claude\.(?:com|ai)/claude-code", re.IGNORECASE),
        "a link to an AI tool's page",
    ),
]


def problems(message: str) -> list[str]:
    """What is wrong with one commit message, as short phrases; empty when it is fine."""
    found: list[str] = []
    for line in message.splitlines():
        for pattern, label in PATTERNS:
            if pattern.search(line) and label not in found:
                found.append(label)
    return found


def commit_messages(base: str, head: str) -> list[tuple[str, str]]:
    """The (short sha, full message) of every commit in BASE..HEAD, oldest last."""
    out = subprocess.run(
        ["git", "log", "--format=%h%x00%B%x01", f"{base}..{head}"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    commits = []
    for chunk in out.split("\x01"):
        chunk = chunk.strip("\n")
        if not chunk:
            continue
        sha, _, message = chunk.partition("\x00")
        commits.append((sha, message))
    return commits


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Check commit messages for AI attribution.")
    parser.add_argument("--base", required=True, help="the commit the branch started from")
    parser.add_argument("--head", required=True, help="the last commit to check")
    args = parser.parse_args(argv)
    bad = []
    commits = commit_messages(args.base, args.head)
    for sha, message in commits:
        issues = problems(message)
        if issues:
            bad.append((sha, issues))
    if not bad:
        print(f"Checked {len(commits)} commit messages: no AI attribution.")
        return 0
    print("AI attribution found in commit messages:", file=sys.stderr)
    for sha, issues in bad:
        print(f"  {sha}: {', '.join(issues)}", file=sys.stderr)
    print(
        "\nRemove the line from each commit (git rebase -i, then reword) and push again. "
        "Record AI use in the pull request's AI usage section, never in a commit.",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
