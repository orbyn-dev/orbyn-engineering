#!/usr/bin/env python3
"""Tests for the commit message check that CI runs on every pull request."""

import subprocess
import tempfile
import unittest
from pathlib import Path

from check_commit_trailers import commit_messages, problems


class AcceptedMessages(unittest.TestCase):
    def test_ordinary_messages_pass(self):
        for message in [
            "feat(web): resize the preview page from its device toolbar",
            "fix(core): keep the composer focused after a send\n\nThe draft was cleared on blur.",
            "docs: explain why the title check exists",
            "Merge pull request #12 from orbyn-dev/fix/thing\n\nfix(web): thing",
            "Co-authored-by: Jane Doe <jane@example.com>",
        ]:
            with self.subTest(message=message):
                self.assertEqual(problems(message), [])

    def test_naming_a_tool_as_the_subject_is_not_attribution(self):
        for message in [
            "fix(codex): wait for tools before the first turn",
            "feat(web): show the claude usage limit",
            "fix(core): time the compact offer by the cache lifetime Claude reports",
            "docs: Claude Code reads skills from its own folder",
        ]:
            with self.subTest(message=message):
                self.assertEqual(problems(message), [])

    def test_the_words_inside_a_sentence_are_not_a_generated_with_line(self):
        for message in [
            "build: the types are generated with ts-rs and checked in",
            "fix(web): files generated with the old script are skipped",
        ]:
            with self.subTest(message=message):
                self.assertEqual(problems(message), [])


class RejectedMessages(unittest.TestCase):
    def test_a_coauthor_trailer_naming_an_ai_tool_fails(self):
        for message in [
            "feat: x\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
            "feat: x\n\nco-authored-by: Claude <claude@example.com>",
            "feat: x\n\nCo-authored-by: GitHub Copilot <copilot@github.com>",
            "feat: x\n\nCo-Authored-By: Codex <codex@openai.com>",
            "feat: x\n\nCo-Authored-By: ChatGPT <bot@example.com>",
            "feat: x\n\nCo-Authored-By: Cursor Agent <cursor@example.com>",
            "feat: x\n\nCo-Authored-By: Gemini <g@google.com>",
        ]:
            with self.subTest(message=message):
                self.assertTrue(problems(message), message)

    def test_a_vendor_address_fails_even_without_the_trailer_keyword(self):
        self.assertTrue(problems("feat: x\n\nThanks <noreply@anthropic.com>"))

    def test_a_generated_with_line_fails(self):
        for message in [
            "feat: x\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)",
            "feat: x\n\nGenerated with Claude Code",
            "feat: x\n\n> Generated by an assistant",
            "feat: x\n\n  generated with codex",
        ]:
            with self.subTest(message=message):
                self.assertTrue(problems(message), message)

    def test_a_link_to_an_ai_tool_page_fails(self):
        self.assertTrue(problems("feat: x\n\nSee https://claude.com/claude-code"))

    def test_each_problem_is_reported_once(self):
        message = (
            "feat: x\n\n"
            "Co-Authored-By: Claude <noreply@anthropic.com>\n"
            "Co-Authored-By: Claude <noreply@anthropic.com>"
        )
        found = problems(message)
        self.assertEqual(len(found), len(set(found)))


class ReadingAGitRange(unittest.TestCase):
    def test_only_the_commits_after_the_base_are_checked(self):
        with tempfile.TemporaryDirectory() as folder:
            repo = Path(folder)

            def git(*args):
                subprocess.run(
                    ["git", "-c", "user.name=T", "-c", "user.email=t@example.com", *args],
                    cwd=repo,
                    check=True,
                    capture_output=True,
                )

            git("init", "-q", "-b", "main")
            git("commit", "-q", "--allow-empty", "-m", "old\n\nCo-Authored-By: Claude <x@y.z>")
            base = subprocess.run(
                ["git", "rev-parse", "HEAD"], cwd=repo, capture_output=True, text=True, check=True
            ).stdout.strip()
            git("commit", "-q", "--allow-empty", "-m", "feat: clean one")
            git("commit", "-q", "--allow-empty", "-m", "feat: two\n\nGenerated with Claude Code")
            import os

            old = os.getcwd()
            os.chdir(repo)
            try:
                commits = commit_messages(base, "HEAD")
            finally:
                os.chdir(old)
            self.assertEqual(len(commits), 2)
            flagged = [sha for sha, message in commits if problems(message)]
            self.assertEqual(len(flagged), 1)


if __name__ == "__main__":
    unittest.main()
