import { expect, test, type Page } from "@playwright/test";
import { startProject, type Service } from "./service";

/**
 * A37: the command palette's search over a real `orbynd`. The pull-request group is read first while the forge is slow,
 * so the palette's reading note is observed on the real route; the unreadable-forge note and its Retry stay
 * component-tested because `GET /api/pulls` answers 200 with a per-project `failed` list instead of failing the whole
 * read. The same spec then searches a thread by title, project and worktree branch, an open pull request by title, head
 * branch and project from the service's own pull list through the stand-in `gh`, and picks a thread to see frecency
 * rank it first (browser storage keeps row ids and times only).
 */

const WINDOW = { width: 1500, height: 900 };
const PAGE_READY = 30_000;

let service: Service;
let projectId: string;
let titleThread = "";
let branchThread = "";
let branch = "";

const palette = (page: Page) => page.getByRole("dialog", { name: "Command palette" });
const query = (dialog: ReturnType<typeof palette>) => dialog.getByRole("combobox", { name: "Search" });

/** Opens the palette and types a query. */
async function search(page: Page, text: string) {
  await page.keyboard.press("ControlOrMeta+k");
  const dialog = palette(page);
  await expect(dialog).toBeVisible();
  await query(dialog).fill(text);
  return dialog;
}

/** A thread's page, with its composer ready. */
async function openThread(page: Page) {
  await page.setViewportSize(WINDOW);
  await page.goto(`${service.page}#/threads/${titleThread}`);
  await expect(page.getByRole("textbox", { name: /^Message/ })).toBeVisible({ timeout: PAGE_READY });
}

test.beforeAll(async () => {
  ({ service, projectId } = await startProject({
    fakeEngines: true,
    forge: [
      { number: 42, title: "Fix the login", headRefName: "fix/login" },
      { number: 77, title: "Tidy the docs", headRefName: "docs/tidy" },
    ],
  }));
  const create = async (title: string, worktree: string | null) =>
    (await service.api<{ id: string }>("POST", "/api/threads", {
      project_id: projectId, engine: "codex", model: null, title, worktree, skill_profile: null,
    })).id;
  titleThread = await create("Palette evidence thread", null);
  branchThread = await create("Branch evidence thread", "palette-evidence");
  // The thread's worktree branch is generated by the service; the palette searches the thread's own worktree branch.
  await expect
    .poll(async () => {
      const thread = await service.api<{ title: string; worktree?: { branch?: string } | null }>("GET", `/api/threads/${branchThread}`);
      branch = thread.worktree?.branch ?? "";
      return branch;
    }, { timeout: 20_000 })
    .not.toBe("");
});

test.afterAll(async () => {
  await service?.stop();
});

test("the pull-request group says it is reading while the forge answers", async ({ page }) => {
  await openThread(page);
  // The forge is slow for this first read, as a real one is: the palette says it is looking until the rows arrive.
  service.ghEdit(0, { delayMs: 1_500 });
  const dialog = await search(page, "Fix the login");
  await expect(dialog.getByText("Looking for pull requests…")).toBeVisible({ timeout: 5_000 });
  service.ghEdit(0, { delayMs: 0 });
  await expect(dialog.getByRole("button", { name: /Fix the login/ })).toBeVisible({ timeout: 20_000 });
});

test("a thread is found by title, project and branch, and a picked thread ranks first", async ({ page }) => {
  await openThread(page);

  // Title, and the Threads group it sits in.
  const dialog = await search(page, "Palette evidence");
  await expect(dialog.getByText("Threads", { exact: true })).toBeVisible();
  await expect(dialog.getByRole("button", { name: /Palette evidence thread/ })).toBeVisible();

  // The project name finds the thread (its extra search words carry the project and the branch).
  await query(dialog).fill("my-repo");
  await expect(dialog.getByRole("button", { name: /Palette evidence thread/ })).toBeVisible();

  // The worktree branch finds the other thread.
  await query(dialog).fill(branch);
  await expect(dialog.getByRole("button", { name: /Branch evidence thread/ })).toBeVisible();

  // Picking a thread is remembered: for a query both threads match, the picked one is then ranked first. Pick the one that is
  // NOT first now, so the ranking can only have moved because of the pick.
  await query(dialog).fill("evidence thread");
  const matches = dialog.locator("button").filter({ hasText: "evidence thread" });
  await expect(matches).toHaveCount(2);
  const firstBefore = await matches.first().innerText();
  const pickPalette = !firstBefore.includes("Palette evidence thread");
  const picked = pickPalette ? "Palette evidence thread" : "Branch evidence thread";
  await dialog.getByRole("button", { name: new RegExp(picked) }).click();
  await expect(page).toHaveURL(new RegExp(pickPalette ? titleThread : branchThread));
  const again = await search(page, "evidence thread");
  await expect(again.locator("button").filter({ hasText: "evidence thread" }).first()).toContainText(picked);
  // What frecency keeps is row ids and times only, in this window's own storage.
  const stored = JSON.parse((await page.evaluate(() => localStorage.getItem("orbyn.palette.frecency"))) ?? "{}") as Record<string, unknown>;
  expect(Object.keys(stored)).toContain(pickPalette ? titleThread : branchThread);
  expect(Object.values(stored).flat().every((stamp) => typeof stamp === "number")).toBe(true);
});

test("open pull requests are found by title, head branch and project", async ({ page }) => {
  await openThread(page);

  // The Pull requests group, with the number in the row.
  const dialog = await search(page, "Fix the login");
  const pull = dialog.getByRole("button", { name: /Fix the login/ });
  await expect(pull).toBeVisible({ timeout: 20_000 });
  await expect(pull).toContainText("#42");
  await expect(dialog.getByText("Pull requests", { exact: true })).toBeVisible();

  // The head branch, and the project the pull request belongs to.
  await query(dialog).fill("fix/login");
  await expect(dialog.getByRole("button", { name: /Fix the login/ })).toBeVisible();
  await expect(dialog.getByRole("button", { name: /Tidy the docs/ })).toHaveCount(0);
  await query(dialog).fill("my-repo");
  await expect(dialog.getByRole("button", { name: /Fix the login/ })).toBeVisible();
});
